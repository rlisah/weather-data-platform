MERGE INTO WEATHER_DATA_PLATFORM.GOLD.WEATHER_METRICS AS T

USING (
    SELECT
        CITY,
        WEATHER_DATE,
        TEMP_MAX_C,
        TEMP_MIN_C,

        ROUND(
            (TEMP_MAX_C + TEMP_MIN_C) / 2, 2
        ) AS TEMP_MIDPOINT_C,

        ROUND(
            TEMP_MAX_C - TEMP_MIN_C, 2
        ) AS AMPLITUDE_TERMICA_C,

        PRECIPITATION_MM,

        CASE
            WHEN PRECIPITATION_MM IS NULL THEN 'SEM DADOS'
            WHEN PRECIPITATION_MM = 0 THEN 'SEM CHUVA'
            WHEN PRECIPITATION_MM <= 2 THEN 'CHUVA LEVE'
            WHEN PRECIPITATION_MM <= 10 THEN 'CHUVA MODERADA'
            ELSE 'CHUVA MAIS INTENSA'
        END AS CLASSIFICACAO_CHUVA

    FROM WEATHER_DATA_PLATFORM.SILVER.WEATHER_DAILY
) AS S

ON T.CITY = S.CITY
AND T.WEATHER_DATE = S.WEATHER_DATE

WHEN MATCHED THEN UPDATE SET
    T.TEMP_MAX_C = S.TEMP_MAX_C,
    T.TEMP_MIN_C = S.TEMP_MIN_C,
    T.TEMP_MIDPOINT_C = S.TEMP_MIDPOINT_C,
    T.AMPLITUDE_TERMICA_C = S.AMPLITUDE_TERMICA_C,
    T.PRECIPITATION_MM = S.PRECIPITATION_MM,
    T.CLASSIFICACAO_CHUVA = S.CLASSIFICACAO_CHUVA,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    CITY,
    WEATHER_DATE,
    TEMP_MAX_C,
    TEMP_MIN_C,
    TEMP_MIDPOINT_C,
    AMPLITUDE_TERMICA_C,
    PRECIPITATION_MM,
    CLASSIFICACAO_CHUVA,
    UPDATED_AT
)
VALUES (
    S.CITY,
    S.WEATHER_DATE,
    S.TEMP_MAX_C,
    S.TEMP_MIN_C,
    S.TEMP_MIDPOINT_C,
    S.AMPLITUDE_TERMICA_C,
    S.PRECIPITATION_MM,
    S.CLASSIFICACAO_CHUVA,
    CURRENT_TIMESTAMP()
);
