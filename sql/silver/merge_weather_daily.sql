MERGE INTO WEATHER_DATA_PLATFORM.SILVER.WEATHER_DAILY T
USING (
    SELECT
        B.CITY,
        TRY_TO_DATE(D.VALUE::STRING) AS WEATHER_DATE,
        TRY_TO_DOUBLE(
            B.PAYLOAD:daily:temperature_2m_max[D.INDEX]::STRING
        ) AS TEMP_MAX_C,
        TRY_TO_DOUBLE(
            B.PAYLOAD:daily:temperature_2m_min[D.INDEX]::STRING
        ) AS TEMP_MIN_C,
        TRY_TO_DOUBLE(
            B.PAYLOAD:daily:precipitation_sum[D.INDEX]::STRING
        ) AS PRECIPITATION_MM
    FROM WEATHER_DATA_PLATFORM.BRONZE.WEATHER_RAW B,
    LATERAL FLATTEN(INPUT => B.PAYLOAD:daily:time) D
    WHERE B.SOURCE = 'OPEN_METEO'
      AND TRY_TO_DATE(D.VALUE::STRING) IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY B.CITY, D.VALUE::STRING
        ORDER BY B.INGESTED_AT DESC, B.INGESTION_ID DESC
    ) = 1
) S
ON T.CITY = S.CITY
AND T.WEATHER_DATE = S.WEATHER_DATE

WHEN MATCHED THEN UPDATE SET
    T.TEMP_MAX_C = S.TEMP_MAX_C,
    T.TEMP_MIN_C = S.TEMP_MIN_C,
    T.PRECIPITATION_MM = S.PRECIPITATION_MM,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    CITY,
    WEATHER_DATE,
    TEMP_MAX_C,
    TEMP_MIN_C,
    PRECIPITATION_MM,
    UPDATED_AT
)
VALUES (
    S.CITY,
    S.WEATHER_DATE,
    S.TEMP_MAX_C,
    S.TEMP_MIN_C,
    S.PRECIPITATION_MM,
    CURRENT_TIMESTAMP()
);
